import { chromium } from "playwright";
const [email, pass, out] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
p.on("dialog", (d) => d.accept());
await p.goto("http://localhost:3002/login", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await p.fill('input[type="email"]', email);
await p.fill('input[type="password"]', pass);
await p.keyboard.press("Enter");
await p.waitForTimeout(5000);
const open = async () => {
  await p.goto("http://localhost:3002/admin/lesson-import/curriculum", { waitUntil: "networkidle" });
  await p.getByRole("tab", { name: "New plan" }).click();
  await p.waitForTimeout(800);
};
const names = () => p.getByLabel("Lesson name").evaluateAll((els) => els.slice(0, 5).map((e) => e.value));
await open();
await p.getByRole("button", { name: "Start again" }).click();
await p.waitForTimeout(1500);
console.log("start:", await names());
await p.getByLabel("Lesson name").first().fill("Renamed lesson");
const row1 = p.getByLabel("Lesson name").nth(1);
await row1.hover();
await p.getByRole("button", { name: "Move up" }).nth(1).click();
console.log("after move up:", await names());
await p.getByLabel("Lesson name").nth(2).hover();
await p.getByRole("button", { name: "Add a note" }).nth(2).click();
await p.keyboard.type("A note I typed");
const sec = p.getByLabel("Section name").nth(1);
await sec.hover();
await p.getByRole("button", { name: "Move section left" }).nth(1).click();
console.log("sections:", await p.getByLabel("Section name").evaluateAll((els) => els.slice(0, 3).map((e) => e.value)));
// move first lesson (now "Check Your Market Page") to Lead Engine
await p.getByLabel("Lesson name").first().hover();
await p.getByLabel("Move lesson to another section").first().selectOption({ label: "Get Calls › Lead Engine" });
await p.getByRole("button", { name: "Lesson", exact: true }).first().click();
await p.getByLabel("Lesson name").nth(3).fill("Brand new lesson");
await p.waitForTimeout(2000);
console.log("status:", await p.getByText(/All changes saved|Saving|Could not|Sign in/).first().textContent());
await open();
console.log("after reload:", await names());
console.log("notes:", await p.getByLabel("Lesson note").evaluateAll((els) => els.slice(0, 2).map((e) => e.value)));
const lead = await p.getByLabel("Lesson name").evaluateAll((els) => els.map((e) => e.value).filter((v) => /Market Page|Brand new/.test(v)));
console.log("moved/added present:", lead);
await p.getByLabel("Lesson name").nth(1).hover();
await p.screenshot({ path: out, clip: { x: 220, y: 380, width: 1220, height: 420 } });
await p.getByRole("button", { name: "Start again" }).click();
await p.waitForTimeout(2000);
await open();
console.log("reset:", await names());
await b.close();
