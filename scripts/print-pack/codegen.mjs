// Bakes the brand logos and the Lucide icon shapes into src/lib/printPack/generated.js,
// so the drawing code needs no file system and runs in the browser as well as in Node.
//   node scripts/print-pack/codegen.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "src/lib/printPack/generated.js");

const logoInner = (file) =>
  fs.readFileSync(path.join(ROOT, file), "utf8").replace(/^[\s\S]*?<\/desc>/, "").replace(/<\/svg>\s*$/, "");

const ICON_DIR = path.join(ROOT, "node_modules/lucide-react/dist/esm/icons");
function iconNode(name) {
  const src = fs.readFileSync(path.join(ICON_DIR, `${name}.js`), "utf8");
  const alias = src.match(/export \{ default \} from '\.\/([\w-]+)\.js'/);
  if (alias) return iconNode(alias[1]);
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!m) throw new Error(`No icon data in ${name}`);
  return Function(`"use strict"; return (${m[1]});`)().map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}
const ICONS = ["activity", "compass", "target", "calendar-check-2", "banknote", "megaphone", "cog", "bar-chart-3", "network", "users", "flag"];

const out = `// GENERATED by scripts/print-pack/codegen.mjs. Do not edit by hand.
// Sources: public/profit-coach-logo.svg, public/brand/profit-coach-logo-white.svg, lucide-react icons.

export const LOGO_COLOUR = ${JSON.stringify(logoInner("public/profit-coach-logo.svg"))};

export const LOGO_WHITE = ${JSON.stringify(logoInner("public/brand/profit-coach-logo-white.svg"))};

export const ICON_NODES = ${JSON.stringify(Object.fromEntries(ICONS.map((n) => [n, iconNode(n)])), null, 1)};
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} (${(out.length / 1024).toFixed(0)} KB)`);
